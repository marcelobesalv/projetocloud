def sku_variante(sku: str, v: dict) -> str:
    partes = [sku]
    for campo in ("switch", "layout", "cor"):
        if v.get(campo):
            partes.append(v[campo].upper().replace(" ", "").replace("/", "-"))
    return "-".join(partes)
